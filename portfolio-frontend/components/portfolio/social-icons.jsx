import { Globe, Mail } from 'lucide-react'
import { getSocialPlatform } from '@/lib/social-platforms'
import { TechIcon } from './tech-icon'

/**
 * Icon for one `social_links` platform.
 *
 * Three rendering paths, because the platform set is not uniform:
 *   - a Simple Icons slug renders through TechIcon, the same component Skills
 *     and API Showcase use, so brand marks stay consistent site-wide;
 *   - LinkedIn falls back to the hand-written mark below, because Simple Icons
 *     withdrew that logo over trademark policy and there is no slug to request;
 *   - email/website are not brands, so they take a generic lucide glyph.
 *
 * `tone="current"` on the TechIcon path is deliberate: these sit in bordered
 * circles that already colour-shift on hover, and painting each mark its own
 * brand colour would fight that. Returns null for an unknown platform so
 * callers can filter with `usableSocialLinks` and never draw an empty circle.
 */
export function SocialIcon({ platform, className = 'h-5 w-5' }) {
  const descriptor = getSocialPlatform(platform)
  if (!descriptor) return null

  if (descriptor.iconSlug) {
    return <TechIcon slug={descriptor.iconSlug} title={descriptor.label} tone="current" className={className} />
  }

  if (platform === 'linkedin') return <LinkedinIcon className={className} />
  if (platform === 'email') return <Mail className={className} aria-hidden="true" />

  return <Globe className={className} aria-hidden="true" />
}

